#!/usr/bin/env bash
# One-command first-time AWS deploy: bootstrap remote state → terraform apply →
# build/push images and roll ECS services.
#
# Usage:
#   make aws-first-deploy PREFIX=yourname
#   ./scripts/aws-first-deploy.sh --help
#
# Env (all optional unless noted):
#   PREFIX              Globally unique state-bucket prefix (required non-interactive)
#   AWS_REGION          Default: us-east-2
#   ENVIRONMENT         Terraform env dir: beta (default) or prod
#   YES                 Set to 1 to skip confirmation prompts
#   SKIP_BOOTSTRAP      Set to 1 when the S3 bucket + lock table already exist
#   SKIP_DEPLOY         Set to 1 to stop after terraform apply (no image push)
#   DOMAIN_NAME         Optional custom domain for HTTPS (TF_VAR_domain_name)
#   ROUTE53_ZONE_ID     Route53 hosted zone for DOMAIN_NAME
#   TF_VAR_*            Pre-set secrets skip auto-generation
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

ENVIRONMENT="${ENVIRONMENT:-beta}"
AWS_REGION="${AWS_REGION:-us-east-2}"
YES="${YES:-0}"
SKIP_BOOTSTRAP="${SKIP_BOOTSTRAP:-0}"
SKIP_DEPLOY="${SKIP_DEPLOY:-0}"
SECRETS_FILE="${REPO_ROOT}/.aws-first-deploy-secrets.env"

usage() {
  cat <<'EOF'
HeadStart first-time AWS deploy (bootstrap → terraform → deploy).

Quick start:
  export AWS_REGION=us-east-2
  make aws-first-deploy PREFIX=your-unique-name

Flags:
  --help              Show this help
  --check             Verify prerequisites and AWS credentials only
  --yes, -y           Auto-approve terraform apply (no prompt)
  --skip-bootstrap    Skip S3/DynamoDB state bootstrap
  --skip-deploy       Provision infra only; skip image build/push

Environment variables: PREFIX, AWS_REGION, ENVIRONMENT, YES=1, SKIP_BOOTSTRAP=1,
SKIP_DEPLOY=1, DOMAIN_NAME, ROUTE53_ZONE_ID, TF_VAR_db_password, TF_VAR_jwt_secret,
TF_VAR_credentials_secret_key, TF_VAR_smtp_host, TF_VAR_smtp_user, TF_VAR_smtp_password,
TF_VAR_smtp_from.

Secrets generated by this script are saved to .aws-first-deploy-secrets.env
(gitignored). Store a copy somewhere safe — they cannot be recovered from Terraform.
EOF
}

require_tool() {
  have "$1" || die "'$1' is required. See docs/deploying-to-aws.md#prerequisites."
}

check_prerequisites() {
  require_tool aws
  require_tool terraform
  require_tool openssl
  require_tool make
  require_tool git
  if [[ "${SKIP_DEPLOY}" != "1" ]]; then
    require_tool docker
    docker info >/dev/null 2>&1 || die "Docker is not running. Start Docker before deploying images."
  fi
}

check_aws_credentials() {
  log "Checking AWS credentials"
  aws sts get-caller-identity --region "${AWS_REGION}" >/dev/null \
    || die "AWS credentials are not configured. Run 'aws configure' or set AWS_* env vars."
}

validate_prefix() {
  local prefix="$1"
  [[ -n "${prefix}" ]] || die "PREFIX is required (globally unique, e.g. your-github-handle)."
  [[ "${prefix}" =~ ^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$ ]] \
    || die "PREFIX must be 3–63 chars, lowercase alphanumeric and hyphens only."
}

prompt_prefix() {
  if [[ -n "${PREFIX:-}" ]]; then
    return
  fi
  if [[ ! -t 0 ]]; then
    die "PREFIX is required in non-interactive mode. Example: make aws-first-deploy PREFIX=yourname"
  fi
  echo
  echo "Choose a globally unique PREFIX for the Terraform state bucket."
  echo "Example: my-github-handle  →  bucket my-github-handle-headstart-tfstate"
  read -r -p "PREFIX: " PREFIX
  validate_prefix "${PREFIX}"
}

confirm_apply() {
  if [[ "${YES}" == "1" ]]; then
    return
  fi
  if [[ ! -t 0 ]]; then
    die "Refusing to run terraform apply without confirmation in non-interactive mode. Set YES=1 to proceed."
  fi
  echo
  warn "This creates billable AWS resources (VPC, ALB, ECS Fargate, RDS, ElastiCache, ECR)."
  warn "The beta stack is not free-tier-only. See docs/deploying-to-aws.md for cost notes."
  read -r -p "Continue with terraform apply? [y/N] " reply
  [[ "${reply}" =~ ^[Yy]$ ]] || die "Aborted."
}

ensure_tf_secrets() {
  local generated=0

  if [[ -z "${TF_VAR_db_password:-}" ]]; then
    export TF_VAR_db_password="$(openssl rand -base64 24)"
    generated=1
  fi
  if [[ -z "${TF_VAR_jwt_secret:-}" ]]; then
    export TF_VAR_jwt_secret="$(openssl rand -hex 32)"
    generated=1
  fi
  if [[ -z "${TF_VAR_credentials_secret_key:-}" ]]; then
    export TF_VAR_credentials_secret_key="$(openssl rand -hex 32)"
    generated=1
  fi
  if [[ -z "${TF_VAR_ntfy_default_topic:-}" || "${TF_VAR_ntfy_default_topic}" == "headstart-change-me" ]]; then
    export TF_VAR_ntfy_default_topic="jobs-$(openssl rand -hex 4)"
    generated=1
  fi

  if [[ "${generated}" == "1" ]]; then
    log "Writing generated secrets to ${SECRETS_FILE} (gitignored)"
    umask 077
    cat >"${SECRETS_FILE}" <<EOF
# Generated by scripts/aws-first-deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Store a backup somewhere safe. Do not commit this file.
export TF_VAR_db_password='${TF_VAR_db_password}'
export TF_VAR_jwt_secret='${TF_VAR_jwt_secret}'
export TF_VAR_credentials_secret_key='${TF_VAR_credentials_secret_key}'
export TF_VAR_ntfy_default_topic='${TF_VAR_ntfy_default_topic}'
EOF
    warn "Back up ${SECRETS_FILE} — these values are not shown again."
  fi
}

apply_optional_domain() {
  if [[ -n "${DOMAIN_NAME:-}" ]]; then
    export TF_VAR_domain_name="${DOMAIN_NAME}"
  fi
  if [[ -n "${ROUTE53_ZONE_ID:-}" ]]; then
    export TF_VAR_route53_zone_id="${ROUTE53_ZONE_ID}"
  fi
}

run_bootstrap() {
  local bucket="$1"
  if [[ "${SKIP_BOOTSTRAP}" == "1" ]]; then
    log "Skipping state bootstrap (SKIP_BOOTSTRAP=1)"
    return
  fi
  if aws s3api head-bucket --bucket "${bucket}" 2>/dev/null; then
    log "State bucket ${bucket} already exists — skipping bootstrap"
    return
  fi
  "${REPO_ROOT}/scripts/terraform-bootstrap-state.sh" "${PREFIX}" "${AWS_REGION}"
}

run_terraform() {
  local bucket="$1"
  local tf_dir="${REPO_ROOT}/devops/terraform/environments/${ENVIRONMENT}"

  [[ -d "${tf_dir}" ]] || die "Unknown ENVIRONMENT '${ENVIRONMENT}' (missing ${tf_dir})"

  log "Terraform init (${ENVIRONMENT}, bucket=${bucket})"
  terraform -chdir="${tf_dir}" init \
    -backend-config="bucket=${bucket}" \
    -backend-config="region=${AWS_REGION}" \
    -backend-config="dynamodb_table=headstart-tflock" \
    -reconfigure

  confirm_apply

  log "Terraform apply (${ENVIRONMENT})"
  terraform -chdir="${tf_dir}" apply -auto-approve
}

run_deploy() {
  if [[ "${SKIP_DEPLOY}" == "1" ]]; then
    log "Skipping image deploy (SKIP_DEPLOY=1)"
    return
  fi

  log "Building, pushing images, and rolling ECS services"
  # shellcheck disable=SC1090
  eval "$("${REPO_ROOT}/scripts/aws-deploy-env.sh" "${ENVIRONMENT}")"
  "${REPO_ROOT}/scripts/deploy.sh"
}

print_summary() {
  local tf_dir="${REPO_ROOT}/devops/terraform/environments/${ENVIRONMENT}"
  local app_url alb_dns

  app_url="$(terraform -chdir="${tf_dir}" output -raw app_url 2>/dev/null || true)"
  alb_dns="$(terraform -chdir="${tf_dir}" output -raw alb_dns_name 2>/dev/null || true)"
  [[ -n "${app_url}" ]] || app_url="http://${alb_dns}"

  echo
  ok "First-time deploy finished."
  echo
  echo "  App URL:     ${app_url}"
  echo "  API health:  ${app_url}/api/v1/health"
  echo "  API docs:    ${app_url}/docs"
  echo
  echo "Next: open the app URL and register — the first user becomes admin."
  echo "Before a public launch, work through docs/launch-checklist.md."
  echo "See docs/getting-started.md from step 2."
  echo
  echo "Ongoing deploys from the repo root:"
  echo "  eval \"\$(make aws-deploy-env ENVIRONMENT=${ENVIRONMENT})\""
  echo "  make deploy"
  if [[ -f "${SECRETS_FILE}" ]]; then
    echo
    warn "Secrets saved in ${SECRETS_FILE} — back them up and never commit that file."
  fi
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --help|-h)
      usage
      exit 0
      ;;
    --check)
      check_prerequisites
      check_aws_credentials
      ok "Prerequisites OK."
      exit 0
      ;;
    --yes|-y)
      YES=1
      ;;
    --skip-bootstrap)
      SKIP_BOOTSTRAP=1
      ;;
    --skip-deploy)
      SKIP_DEPLOY=1
      ;;
    *)
      die "Unknown option: $1 (try --help)"
      ;;
  esac
  shift
done

check_prerequisites
check_aws_credentials
prompt_prefix
validate_prefix "${PREFIX}"

BUCKET="${PREFIX}-headstart-tfstate"
TF_DIR="${REPO_ROOT}/devops/terraform/environments/${ENVIRONMENT}"

log "First-time deploy: environment=${ENVIRONMENT} region=${AWS_REGION} bucket=${BUCKET}"

run_bootstrap "${BUCKET}"
ensure_tf_secrets
apply_optional_domain
run_terraform "${BUCKET}"
run_deploy
print_summary
